/**
 * The RPC group a host serves over its unix socket (effect/rpc, NDJSON).
 * Every payload, result and error is a Schema, so typed failures
 * (`TurnFailure` members, `AgentError`, `EventsTrimmed`) arrive as the same
 * classes on the client.
 *
 * @since 0.1.0
 */
import { Schema } from "effect"
import { Rpc, RpcGroup } from "effect/rpc"
import { Capabilities, SteerOutcome } from "../Agent.ts"
import { AgentError, TurnFailure } from "../AgentError.ts"
import { AgentEvent, TurnSucceeded } from "../AgentEvent.ts"
import { MessageId, SessionId, TurnId } from "../Domain.ts"

/**
 * `subscribeFrom` asked for events the host no longer has: older than its
 * in-memory cache (`HostSpec.maxEvents`) when events aren't persisted
 * (`persistEvents: false`), or when the events file is missing or unreadable.
 *
 * @since 0.1.0
 * @category errors
 */
export class EventsTrimmed extends Schema.TaggedError<EventsTrimmed>()("EventsTrimmed", {
  message: Schema.String,
  /** The `fromSeq` asked for. */
  requested: Schema.Number,
  /** The oldest sequence number still kept. */
  oldest: Schema.Number,
}) {}

/**
 * An event and its position in the session's log (0, 1, 2, ...).
 *
 * @since 0.1.0
 * @category models
 */
export const SeqEvent = Schema.Struct({ seq: Schema.Number, event: AgentEvent })
/**
 * @since 0.1.0
 * @category models
 */
export type SeqEvent = typeof SeqEvent.Type

/**
 * What `Info` returns: the session, the host, and the range of events it can serve.
 *
 * @since 0.1.0
 * @category models
 */
export const HostInfo = Schema.Struct({
  sessionId: SessionId,
  provider: Schema.String,
  location: Schema.NullOr(Schema.String),
  /** The agent process's pid, when it has one. */
  pid: Schema.NullOr(Schema.Number),
  /** The host process's pid. */
  hostPid: Schema.Number,
  capabilities: Capabilities,
  /** The last event's sequence number; -1 before the first event. */
  lastSeq: Schema.Number,
  /** The oldest sequence number `Subscribe` can still serve (0 while the events file is kept). */
  oldestSeq: Schema.Number,
  /** The session has ended (the host is about to exit). */
  ended: Schema.Boolean,
})
/**
 * @since 0.1.0
 * @category models
 */
export type HostInfo = typeof HostInfo.Type

/**
 * `requestId` (here and on `Interrupt`) is generated by the client, once per
 * call: a call retried after a reconnect repeats it, and the host answers a
 * repeated id with the original result (it remembers the last 1 000) instead
 * of acting again.
 */
const Input = { input: Schema.String, requestId: Schema.String }
const TurnError = Schema.Union([TurnFailure, AgentError])

/**
 * The hooks a client can answer for a host.
 *
 * @since 0.1.0
 * @category models
 */
export const HookName = Schema.Literals(["beforeTool", "afterTool", "beforeStop"])
/**
 * @since 0.1.0
 * @category models
 */
export type HookName = typeof HookName.Type

/**
 * A hook's input: `ToolHookInput` (plus `output`/`isError` for `afterTool`); null for `beforeStop`.
 *
 * @since 0.1.0
 * @category models
 */
export const HookCall = Schema.Struct({
  callId: Schema.String,
  name: Schema.String,
  input: Schema.Unknown,
  output: Schema.optionalKey(Schema.String),
  isError: Schema.optionalKey(Schema.Boolean),
})
/**
 * @since 0.1.0
 * @category models
 */
export type HookCall = typeof HookCall.Type

/**
 * The host asks a client to run one of its hooks.
 *
 * @since 0.1.0
 * @category models
 */
export const HookRequest = Schema.TaggedStruct("HookRequest", { hookId: Schema.String, hook: HookName, call: Schema.NullOr(HookCall) })
/**
 * @since 0.1.0
 * @category models
 */
export type HookRequest = typeof HookRequest.Type

/**
 * `HookRequests` items: `Registered` first (the client is answering from now on), then requests.
 *
 * @since 0.1.0
 * @category models
 */
export const HookStreamItem = Schema.Union([Schema.TaggedStruct("Registered", {}), HookRequest])
/**
 * @since 0.1.0
 * @category models
 */
export type HookStreamItem = typeof HookStreamItem.Type

/**
 * @since 0.1.0
 * @category rpc
 */
export class HostRpcs extends RpcGroup.make(
  Rpc.make("Info", { success: HostInfo, error: AgentError }),
  /**
   * Events with `seq >= fromSeq`, then live ones, until the session ends
   * (failing with the session's `AgentError` if it ended in one). `live`
   * prepends the session's `SessionStarted` when it is older than `fromSeq`,
   * as `AgentSession.subscribe` does (`RemoteSession.subscribe` pins `fromSeq`
   * to `Info.lastSeq + 1`, and sets `live` unless the session had ended).
   */
  Rpc.make("Subscribe", {
    payload: { fromSeq: Schema.Number, live: Schema.Boolean },
    success: SeqEvent,
    error: Schema.Union([EventsTrimmed, AgentError]),
    stream: true,
  }),
  Rpc.make("Send", { payload: Input, success: MessageId, error: AgentError }),
  Rpc.make("Steer", { payload: Input, success: SteerOutcome, error: AgentError }),
  Rpc.make("Interrupt", { payload: { requestId: Schema.String }, error: AgentError }),
  /** Graceful: finish queued work, end the session; the host then exits. */
  Rpc.make("End", { error: AgentError }),
  /** Hard: close the session now (killing its processes); the host then exits. */
  Rpc.make("Stop"),
  Rpc.make("Turn", { payload: Input, success: TurnSucceeded, error: TurnError }),
  /** A turn's ending: from the log if it already ended, otherwise when it does. */
  Rpc.make("AwaitTurn", { payload: { turnId: TurnId }, success: TurnSucceeded, error: TurnError }),
  /** The ending of the turn a message landed in, by the `MessageId` that `Send` returned. */
  Rpc.make("AwaitMessage", { payload: { messageId: MessageId }, success: TurnSucceeded, error: TurnError }),
  /**
   * A client that has hooks registers to answer them: the host streams it the
   * hook calls it should run, until the session ends. `clientId` is stable
   * across the client's reconnects (its rank, and requests still waiting, are
   * kept); `timeoutMs` bounds each call the host sends it.
   */
  Rpc.make("HookRequests", {
    payload: { clientId: Schema.String, hooks: Schema.Array(HookName), timeoutMs: Schema.Number },
    success: HookStreamItem,
    stream: true,
  }),
  /** A hook's result: text to add, or null for none. Late or repeated answers are ignored. */
  Rpc.make("HookResponse", { payload: { hookId: Schema.String, result: Schema.NullOr(Schema.String) } }),
  /** Internal, tests only (`HostSpec.testInvokeHook`): run a hook through the bridge as the agent would. */
  Rpc.make("TestInvokeHook", {
    payload: { requestId: Schema.String, hook: HookName, call: Schema.NullOr(HookCall) },
    success: Schema.NullOr(Schema.String),
    error: AgentError,
  }),
) {}
